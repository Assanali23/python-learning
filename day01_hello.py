# День 1 — моя первая программа на Python
# Запуск:  python day01_hello.py

# print() выводит текст на экран
print("Привет! Это моя первая программа.")

# Переменная — это "коробка" с именем, в которой хранится значение
name = "Адильбек"        # строка (текст) — в кавычках
year = 2026              # число — без кавычек

# f-строка (буква f перед кавычками) позволяет вставлять переменные в текст через {}
print(f"Меня зовут {name}, и я начинаю учиться в {year} году.")

# Python умеет считать
print(f"Через 3 года будет {year + 3} год.")
